/** Experimental API. WAV processing currently supports 16-bit integer PCM only. */
export interface AudioEngine {
  /** Normalize samples in place and return the applied linear gain. */
  normalizePeak(samples: Float32Array, targetPeak: number): number;
  /** Return a Hann-windowed one-sided amplitude spectrum for mono PCM. */
  spectrum(samples: Float32Array, sampleRate: number): SpectrumBin[];
  /** Prepare a local WAV into a caller-provided stream. */
  processWav(
    input: Blob,
    output: WritableStream<Uint8Array>,
    options: WavProcessOptions,
  ): Promise<WavProcessResult>;
  /** Yield bounded WAV chunks with offsets on the source frame timeline. */
  chunkWav(input: Blob, options: WavChunkOptions): AsyncGenerator<WavChunk>;
  /** Extract a half-open source-frame range as a WAV blob. */
  extractWav(input: Blob, options: WavExtractOptions): Promise<WavChunk>;
  /** Extract a source time range, rounded outward to whole frames. */
  extractWavSeconds(
    input: Blob,
    options: WavExtractSecondsOptions,
  ): Promise<WavChunk>;
  /** Merge compatible WAV inputs into a caller-provided stream. */
  mergeWav(
    inputs: readonly Blob[],
    output: WritableStream<Uint8Array>,
    options?: WavMergeOptions,
  ): Promise<WavMergeResult>;
  /** Remove source-frame intervals and return a mapping of the retained audio. */
  trimWav(
    input: Blob,
    removed: readonly WavTrimInterval[],
    output: WritableStream<Uint8Array>,
    options?: WavMergeOptions,
  ): Promise<WavTrimResult>;
}

/** Initialize the supplied local WASM bindings and create an engine. */
export async function createAudioEngine(
  bindings: WasmAudioBindings,
): Promise<AudioEngine> {
  try {
    await bindings.default();
  } catch (cause) {
    throw new AudioEngineError(
      "INITIALIZATION_FAILED",
      "Failed to initialize audio engine",
      { cause },
    );
  }
  return {
    normalizePeak(samples, targetPeak) {
      return guardDsp(() => bindings.normalize_pcm_peak(samples, targetPeak));
    },
    spectrum(samples, sampleRate) {
      const values = guardDsp(() =>
        bindings.analyze_spectrum(samples, sampleRate),
      );
      const bins: SpectrumBin[] = [];
      for (let index = 0; index < values.length; index += 2) {
        bins.push({ frequencyHz: values[index], amplitude: values[index + 1] });
      }
      return bins;
    },
    processWav(input, output, options) {
      return processWav(bindings, input, output, options);
    },
    chunkWav(input, options) {
      return chunkWav(input, options);
    },
    extractWav(input, options) {
      return extractWav(input, options);
    },
    extractWavSeconds(input, options) {
      return extractWavSeconds(input, options);
    },
    mergeWav(inputs, output, options) {
      return mergeWav(inputs, output, options);
    },
    trimWav(input, removed, output, options) {
      return trimWav(input, removed, output, options);
    },
  };
}
